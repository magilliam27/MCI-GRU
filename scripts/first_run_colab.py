def sync_to_drive(local_dir: Path, drive_dir: Path) -> int:
    """Copy new or changed files from ``local_dir`` to ``drive_dir``. Never deletes.

    The run itself writes to local disk: snapshot capture publishes with hard links,
    and Colab's Drive mount is not known to support them. Returns the number of files copied.
    """
    local_dir, drive_dir = Path(local_dir), Path(drive_dir)
    copied = 0
    for source in sorted(local_dir.rglob("*")):
        # Capture stages each manifest under a temporary name before publishing it.
        if not source.is_file() or source.name.startswith(".input-manifest-"):
            continue
        target = drive_dir / source.relative_to(local_dir)
        stat = source.stat()
        if target.exists():
            existing = target.stat()
            if existing.st_size == stat.st_size and existing.st_mtime >= stat.st_mtime:
                continue
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        copied += 1
    return copied


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


