def sync_to_drive(local_dir: Path, drive_dir: Path) -> int:
    """Copy new or changed files from ``local_dir`` to ``drive_dir``. Never deletes.

    The run itself writes to local disk: snapshot capture publishes with hard links,
    and Colab's Drive mount is not known to support them. Returns the number of files copied.
    """
    local_dir, drive_dir = Path(local_dir), Path(drive_dir)
    copied = 0
    for source in sorted(local_dir.rglob("*")):
        # Capture stages each manifest under a temporary name before publishing it.
        if not source.is_file() or source.name.startswith(".input-manifest-"):
            continue
        target = drive_dir / source.relative_to(local_dir)
        stat = source.stat()
        if target.exists():
            existing = target.stat()
            if existing.st_size == stat.st_size and existing.st_mtime >= stat.st_mtime:
                continue
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        copied += 1
    return copied


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def run_with_drive_sync(
    command: Sequence[str],
    *,
    cwd: Path,
    local_dir: Path,
    drive_dir: Path,
    every_seconds: float = 600.0,
    env: dict[str, str] | None = None,
    echo: Callable[[str], None] = print,
) -> int:
    """Run ``command``, echo its output, and copy ``local_dir`` to Drive as it goes.

    Copies run on a timer thread, so a slow copy never blocks the run's output
    pipe, and a failed copy (a dropped Drive mount, a full quota) is reported and
    retried at the next tick instead of stopping training. A heartbeat file on
    Drive records the last copy. The final copy runs whatever the exit code.
    """
    local_dir, drive_dir = Path(local_dir), Path(drive_dir)
    heartbeat = drive_dir / "colab_heartbeat.json"
    started = datetime.now(timezone.utc).isoformat()

    def copy_now(state: str, **extra: Any) -> None:
        try:
            copied = sync_to_drive(local_dir, drive_dir) if local_dir.exists() else 0
            write_json(
                heartbeat,
                {
                    "started_at_utc": started,
                    "last_copy_at_utc": datetime.now(timezone.utc).isoformat(),
                    "files_copied": copied,
                    "state": state,
                    **extra,
                },
            )
        except OSError as error:
            echo(f"[drive copy] failed, will retry: {error}")

    stop = threading.Event()

    def copy_periodically() -> None:
        while not stop.wait(every_seconds):
            copy_now("running")

    run_env = dict(os.environ if env is None else env)
    run_env["PYTHONUNBUFFERED"] = "1"
    process = subprocess.Popen(
        list(command),
        cwd=cwd,
        env=run_env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )
    assert process.stdout is not None
    copier = threading.Thread(target=copy_periodically, daemon=True)
    copier.start()
    returncode = None
    try:
        for line in process.stdout:
            echo(line.rstrip("\n"))
        returncode = process.wait()
    finally:
        if returncode is None:
            process.kill()
            returncode = process.wait()
        stop.set()
        copier.join()
        copy_now("finished", returncode=returncode)
    return returncode


