def _source_changes() -> str:
    """Changes git sees under the roots #144 records, untracked files included."""
    from mci_gru.evaluation.execution_provenance import SOURCE_ROOTS

    return _git("status", "--porcelain", "--", *SOURCE_ROOTS)


def _command_run(args: Any) -> int:
    import sys

    full = args.mode == "full"
    prerequisites = admitted_run_prerequisites(REPO_DIR)
    if full and any(not p.present for p in prerequisites):
        print("Refusing a full run: run the prerequisites check to see what is missing.")
        return 1
    if not os.environ.get("FRED_API_KEY", "").strip():
        print("Refusing to run: FRED_API_KEY is not set (Colab secret FRED_API_KEY).")
        return 1
    source_changes = _source_changes()
    if full and source_changes:
        print("Refusing a full run: the checkout's source has changes:\n" + source_changes)
        return 1
    recipe_text = (REPO_DIR / RECIPE_PATH).read_text(encoding="utf-8")
    slug = recipe_slug(recipe_text)
    commit = _git("rev-parse", "HEAD")
    run_tag = args.run_tag or (
        f"{datetime.now(timezone.utc):%Y%m%dT%H%M%SZ}-{args.mode}-{commit[:8]}"
    )
    local_dir = Path(args.local_root) / run_tag
    drive_dir = Path(args.drive_root) / run_tag
    if local_dir.exists() or drive_dir.exists():
        print(f"Refusing to reuse a run folder: {local_dir} or {drive_dir} already exists.")
        return 1
    # Staged again here, so a run never starts on inputs that were not verified.
    # Both steps reuse files already in place after re-hashing them.
    staging = _stage_inputs(args.package_drive_dir, args.eodhd_drive_path)
    overrides = build_run_overrides(
        recipe_overrides(recipe_text),
        run_dir=local_dir,
        experiment_name=slug,
        smoke=not full,
    )
    record = {
        "run_tag": run_tag,
        "mode": args.mode,
        "evidence": EVIDENCE_LABELS[args.mode],
        "recipe_slug": slug,
        "commit": commit,
        "source_changes": source_changes,
        "prerequisites": [
            {"pull_request": p.pull_request, "description": p.description, "present": p.present}
            for p in prerequisites
        ],
        "staging": staging,
        "overrides": overrides,
        "local_dir": str(local_dir),
        "drive_dir": str(drive_dir),
        "fred_api_key_set": True,
        "started_at_utc": datetime.now(timezone.utc).isoformat(),
    }
    local_dir.mkdir(parents=True)
    write_json(local_dir / "colab_run_record.json", record)
    freeze = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True, check=False
    )
    (local_dir / "pip_freeze.txt").write_text(freeze.stdout, encoding="utf-8")
    if args.tag_file:
        Path(args.tag_file).write_text(run_tag + "\n", encoding="utf-8")
    print(f"Run {run_tag}: {record['evidence']}")
    print(f"Local folder: {local_dir}\nDrive copy:   {drive_dir}")
    returncode = run_with_drive_sync(
        [sys.executable, "-u", "run_experiment.py", *overrides],
        cwd=REPO_DIR,
        local_dir=local_dir,
        drive_dir=drive_dir,
        every_seconds=args.sync_every,
    )
    record["finished_at_utc"] = datetime.now(timezone.utc).isoformat()
    record["returncode"] = returncode
    write_json(local_dir / "colab_run_record.json", record)
    try:
        sync_to_drive(local_dir, drive_dir)
    except OSError as error:
        print(f"The last copy to Drive failed ({error}); the run folder is still at {local_dir}")
    print(f"run_experiment.py exited {returncode}; outputs copied to {drive_dir}")
    return returncode


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    check_env = commands.add_parser("check-env")
    check_env.add_argument("--require-gpu", action="store_true")
    prerequisites = commands.add_parser("prerequisites")
    prerequisites.add_argument("--mode", choices=sorted(EVIDENCE_LABELS), required=True)
    stage = commands.add_parser("stage")
    stage.add_argument("--package-drive-dir", default="")
    stage.add_argument("--eodhd-drive-path", default=EODHD_MARKET_DRIVE_PATH)
    run = commands.add_parser("run")
    run.add_argument("--mode", choices=sorted(EVIDENCE_LABELS), required=True)
    run.add_argument("--local-root", required=True)
    run.add_argument("--drive-root", required=True)
    run.add_argument("--run-tag", default="")
    run.add_argument("--sync-every", type=float, default=600.0)
    run.add_argument("--package-drive-dir", default="")
    run.add_argument("--eodhd-drive-path", default=EODHD_MARKET_DRIVE_PATH)
    run.add_argument("--tag-file", default="")
    args = parser.parse_args(argv)
    handler = {
        "check-env": _command_check_env,
        "prerequisites": _command_prerequisites,
        "stage": _command_stage,
        "run": _command_run,
    }[args.command]
    return handler(args)


