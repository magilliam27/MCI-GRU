def recipe_overrides(text: str) -> list[str]:
    """The Hydra overrides in the recipe's override block, in order."""
    match = _OVERRIDE_BLOCK.search(text)
    if match is None:
        raise ValueError("The recipe has no '## Hydra Overrides' text block")
    overrides = [line.strip() for line in match.group(1).splitlines() if line.strip()]
    keys = [override.split("=", 1)[0] for override in overrides]
    duplicates = sorted({key for key in keys if keys.count(key) > 1})
    if duplicates:
        raise ValueError(f"The recipe sets these keys more than once: {duplicates}")
    return overrides


def recipe_slug(text: str) -> str:
    """The recipe slug, the one line in the block under 'Recipe slug:'."""
    match = _SLUG_BLOCK.search(text)
    if match is None:
        raise ValueError("The recipe has no 'Recipe slug:' text block")
    lines = [line.strip() for line in match.group(1).splitlines() if line.strip()]
    if len(lines) != 1:
        raise ValueError(f"The recipe slug block must hold one line, found {len(lines)}")
    return lines[0]


def override_value(overrides: Sequence[str], key: str) -> str | None:
    for override in overrides:
        name, _, value = override.partition("=")
        if name == key:
            return value
    return None


def replace_override(overrides: Sequence[str], key: str, value: str) -> list[str]:
    """Set ``key=value`` in place. Hydra refuses a key given twice, so never append."""
    found = False
    result = []
    for override in overrides:
        if override.partition("=")[0] == key:
            result.append(f"{key}={value}")
            found = True
        else:
            result.append(override)
    if not found:
        raise KeyError(f"The recipe does not set {key}")
    return result


