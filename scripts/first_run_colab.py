def lock_pins(lock_text: str) -> dict[str, str]:
    """``{normalized name: version}`` for every ``name==version`` line of a pip-compile lock."""
    pins = {}
    for line in lock_text.splitlines():
        match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;]+)", line)
        if match:
            pins[re.sub(r"[-_.]+", "-", match.group(1)).lower()] = match.group(2)
    return pins


def lock_mismatches(pins: dict[str, str], installed: Callable[[str], str | None]) -> list[str]:
    """Pins the environment does not satisfy. A local suffix such as ``+cu130`` is allowed."""
    problems = []
    for name, version in sorted(pins.items()):
        found = installed(name)
        if found is None:
            problems.append(f"{name}: not installed (lock pins {version})")
        elif found.split("+", 1)[0] != version:
            problems.append(f"{name}: {found} installed, lock pins {version}")
    return problems


