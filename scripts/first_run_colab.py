def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _check(path: Path, sha256: str, size: int, what: str) -> None:
    observed_size = path.stat().st_size
    observed_sha256 = sha256_of(path)
    if observed_size != size or observed_sha256 != sha256:
        raise StagingError(
            f"{what} at {path} does not match its pin: expected {size} bytes, "
            f"sha256 {sha256}; found {observed_size} bytes, sha256 {observed_sha256}. "
            "Nothing was replaced."
        )


def stage_verified_file(source: Path, target: Path, *, sha256: str, size: int) -> str:
    """Copy ``source`` to ``target`` only if both hold exactly the pinned bytes.

    Returns ``"reused"`` when ``target`` already holds them and ``"copied"`` after a
    copy. A ``target`` with other bytes is never replaced, and a ``source`` with
    other bytes is never copied.
    """
    source, target = Path(source), Path(target)
    if target.exists():
        _check(target, sha256, size, "The file already in place")
        return "reused"
    if not source.exists():
        raise StagingError(f"Missing on Drive: {source}")
    _check(source, sha256, size, "The Drive copy")
    target.parent.mkdir(parents=True, exist_ok=True)
    partial = target.with_name(target.name + ".partial")
    if partial.exists():
        raise StagingError(f"A partial copy from an earlier attempt is in the way: {partial}")
    shutil.copyfile(source, partial)
    _check(partial, sha256, size, "The copy")
    os.replace(partial, target)
    return "copied"


def _git_bytes(repo_dir: Path, *args: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(repo_dir), *args], check=True, capture_output=True
    ).stdout


def align_tracked_line_endings(
    repo_dir: Path, inventory: dict[str, tuple[str, int]], *, package_root: str = PACKAGE_ROOT
) -> list[str]:
    """Give package files that git tracks their pinned bytes in a fresh clone.

    Two of the package's sidecars are tracked in git with LF line endings, while
    the package pins the Windows CRLF bytes they were preserved with. A Linux clone
    therefore holds other bytes at those paths. For each tracked path whose bytes
    differ from its pin, this checks that the committed blob with CRLF line endings
    has exactly the pinned digest and size, records ``text eol=crlf`` for that path
    in ``.git/info/attributes`` (local to this clone), and has git check the path
    out again, which writes those bytes. Git then reports the file unchanged. Any other difference stops. Returns the paths
    it realigned.
    """
    repo_dir = Path(repo_dir)
    aligned = []
    for relative, (sha256, size) in sorted(inventory.items()):
        repo_path = f"{package_root}/{relative}"
        listed = subprocess.run(
            ["git", "-C", str(repo_dir), "ls-files", "--error-unmatch", "--", repo_path],
            capture_output=True,
        )
        if listed.returncode != 0:
            continue
        target = repo_dir / repo_path
        if target.exists() and target.stat().st_size == size and sha256_of(target) == sha256:
            continue
        crlf = re.sub(rb"(?<!\r)\n", b"\r\n", _git_bytes(repo_dir, "show", f"HEAD:{repo_path}"))
        if len(crlf) != size or hashlib.sha256(crlf).hexdigest() != sha256:
            raise StagingError(
                f"{repo_path} is tracked in git with bytes that are not the package's, "
                "even with CRLF line endings. Nothing was changed."
            )
        attributes = repo_dir / ".git" / "info" / "attributes"
        rule = f"/{repo_path} text eol=crlf\n"
        existing = attributes.read_text(encoding="utf-8") if attributes.exists() else ""
        if rule not in existing.splitlines(keepends=True):
            attributes.parent.mkdir(parents=True, exist_ok=True)
            with open(attributes, "a", encoding="utf-8") as handle:
                handle.write(("" if not existing or existing.endswith("\n") else "\n") + rule)
        # Git writes the file itself, so its index records the new stat and the path
        # reads as unchanged; writing the bytes directly leaves a size the index
        # does not match, which git status reports as a change.
        target.unlink(missing_ok=True)
        _git_bytes(repo_dir, "checkout", "--", repo_path)
        if target.stat().st_size != size or sha256_of(target) != sha256:
            raise StagingError(f"{repo_path} did not check out with its pinned bytes.")
        status = _git_bytes(repo_dir, "status", "--porcelain", "--", repo_path)
        if status.strip():
            raise StagingError(f"{repo_path} still reads as changed to git: {status.decode()}")
        aligned.append(relative)
    return aligned


def parse_historical_inventory(raw: bytes) -> dict[str, tuple[str, int]]:
    """``{path: (sha256, size)}`` from a ``sha256  bytes  path`` MANIFEST.txt."""
    inventory: dict[str, tuple[str, int]] = {}
    for number, line in enumerate(raw.decode("utf-8").splitlines(), start=1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split()
        if len(fields) != 3 or not re.fullmatch(r"[0-9a-f]{64}", fields[0]):
            raise StagingError(f"MANIFEST.txt line {number} is not 'sha256 bytes path'")
        sha256, size, path = fields
        if not size.isdigit():
            raise StagingError(f"MANIFEST.txt line {number} has a non-integer size")
        if path in inventory:
            raise StagingError(f"MANIFEST.txt lists {path} twice")
        inventory[path] = (sha256, int(size))
    if not inventory:
        raise StagingError("MANIFEST.txt lists no files")
    return inventory


@dataclass(frozen=True)
class StagedPackage:
    verification: PackageVerification
    outcomes: dict[str, str]
    drive_inventory_sha256: str

    def summary(self) -> dict[str, Any]:
        return {
            "package_id": self.verification.snapshot.manifest.package_id,
            "package_revision": self.verification.snapshot.manifest.package_revision,
            "manifest_sha256": self.verification.snapshot.sha256,
            "drive_inventory_sha256": self.drive_inventory_sha256,
            "files": [
                {
                    "path": observation.record.path,
                    "sha256": observation.sha256,
                    "size_bytes": observation.size_bytes,
                    "staging": self.outcomes[observation.record.path],
                }
                for observation in self.verification.files
            ],
        }


def stage_package(
    repo_dir: Path,
    drive_dir: Path,
    *,
    manifest: str = PACKAGE_MANIFEST,
    manifest_sha256: str = PACKAGE_MANIFEST_SHA256,
    drive_inventory: str = "historical_inventory",
) -> StagedPackage:
    """Stage a preserved package from Drive into ``data/raw`` and verify all of it.

    The Drive copy must carry the inventory the committed manifest vouches for:
    either a ``MANIFEST.txt`` with the digest the manifest records for its historical
    inventory, which must then equal the manifest's file records path for path, hash
    for hash and size for size; or a byte-identical copy of the manifest, whose own
    records are then the inventory. Every staged file must have its pinned bytes, and
    the staged package must pass ``validate_input_package``. Only the
    ``MANIFEST.txt`` route is an independent second inventory.
    """
    repo_dir, drive_dir = Path(repo_dir), Path(drive_dir)
    snapshot = read_input_manifest(repo_dir / manifest, expected_sha256=manifest_sha256)
    declared = {
        record.path: (record.sha256, record.size_bytes) for record in snapshot.manifest.files
    }
    if drive_inventory == "historical_inventory":
        recorded = snapshot.manifest.metadata.get("historical_inventory", {})
        inventory_path = drive_dir / HISTORICAL_INVENTORY_NAME
        expected = (recorded.get("sha256"), recorded.get("size_bytes"))
    elif drive_inventory == "manifest_copy":
        inventory_path = drive_dir / Path(manifest).name
        expected = (snapshot.sha256, len(snapshot.raw_bytes))
    else:
        raise ValueError(f"Unknown Drive inventory kind {drive_inventory!r}")
    if not inventory_path.exists():
        raise StagingError(f"Missing on Drive: {inventory_path}")
    inventory_bytes = inventory_path.read_bytes()
    inventory_sha256 = hashlib.sha256(inventory_bytes).hexdigest()
    if (inventory_sha256, len(inventory_bytes)) != expected:
        raise StagingError(
            f"{inventory_path} is not the inventory the manifest vouches for: expected "
            f"sha256 {expected[0]} ({expected[1]} bytes), found "
            f"{inventory_sha256} ({len(inventory_bytes)} bytes)"
        )
    inventory = (
        parse_historical_inventory(inventory_bytes)
        if drive_inventory == "historical_inventory"
        else dict(declared)
    )
    if inventory != declared:
        raise StagingError(
            "The Drive inventory and the manifest disagree: only on Drive "
            f"{sorted(set(inventory) - set(declared))}, only in the manifest "
            f"{sorted(set(declared) - set(inventory))}, different bytes "
            f"{sorted(p for p in set(inventory) & set(declared) if inventory[p] != declared[p])}"
        )
    package_root = repo_dir / PACKAGE_ROOT
    aligned = (
        align_tracked_line_endings(repo_dir, inventory) if (repo_dir / ".git").exists() else []
    )
    outcomes = {
        path: stage_verified_file(drive_dir / path, package_root / path, sha256=sha256, size=size)
        for path, (sha256, size) in sorted(inventory.items())
    }
    outcomes.update({path: "aligned" for path in aligned})
    verification = validate_input_package(snapshot, package_root, expected_paths=list(inventory))
    return StagedPackage(verification, outcomes, inventory_sha256)


