def build_run_overrides(
    recipe: Sequence[str],
    *,
    run_dir: Path,
    experiment_name: str,
    smoke: bool,
) -> list[str]:
    """The recipe's overrides plus where this run writes; budgets change only for smoke.

    Capture is added only when the recipe does not already select it (main before
    #274). The folder is named explicitly then, because before #274 capture has no
    default folder; from #274 on, the default is the same ``input_snapshots/``.
    MLflow tracking is switched off: ``requirements.lock`` does not carry the
    ``tracking`` extra, and the run's own records do not depend on it.
    """
    overrides = list(recipe)
    if smoke:
        for key, value in SMOKE_BUDGET.items():
            overrides = replace_override(overrides, key, value)
    if override_value(overrides, "data.auxiliary_snapshot_mode") is None:
        overrides += [
            "data.auxiliary_snapshot_mode=capture",
            f"data.auxiliary_snapshot_directory={Path(run_dir) / 'input_snapshots'}",
        ]
    if override_value(overrides, "tracking.enabled") is None:
        overrides.append("tracking.enabled=false")
    else:
        overrides = replace_override(overrides, "tracking.enabled", "false")
    overrides += [
        f"hydra.run.dir={run_dir}",
        f"experiment_name={experiment_name}",
    ]
    return overrides


